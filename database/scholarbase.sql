-- =====================================================================================
--  ScholarBase - Student Record Management System
--  MySQL 8.0+ schema, indexes and sample data.
--
--  Run once from a terminal:   mysql -u root -p < scholarbase.sql
--  WARNING: re-running drops and recreates every ScholarBase table.
--
--  Sample administrator:  username  admin   |   password  Admin@123
--  Change this password from Settings -> Security after your first login.
--  Only a salted PBKDF2 hash is stored - never the plain password.
-- =====================================================================================

CREATE DATABASE IF NOT EXISTS scholarbase CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE scholarbase;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS results;
DROP TABLE IF EXISTS attendance;
DROP TABLE IF EXISTS student_courses;
DROP TABLE IF EXISTS courses;
DROP TABLE IF EXISTS students;
DROP TABLE IF EXISTS admins;
SET FOREIGN_KEY_CHECKS = 1;

-- -------------------------------------------------------------------------------------
-- 1. admins
-- -------------------------------------------------------------------------------------
CREATE TABLE admins (
    id            BIGINT       NOT NULL AUTO_INCREMENT,
    username      VARCHAR(50)  NOT NULL,
    email         VARCHAR(120) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login    DATETIME     NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_admins_username UNIQUE (username),
    CONSTRAINT uq_admins_email    UNIQUE (email)
) ENGINE=InnoDB;

-- -------------------------------------------------------------------------------------
-- 2. students
-- -------------------------------------------------------------------------------------
CREATE TABLE students (
    id              BIGINT       NOT NULL AUTO_INCREMENT,
    full_name       VARCHAR(100) NOT NULL,
    roll_number     VARCHAR(30)  NOT NULL,
    email           VARCHAR(120) NOT NULL,
    phone           VARCHAR(20)  NOT NULL,
    date_of_birth   DATE         NOT NULL,
    gender          ENUM('MALE','FEMALE','OTHER') NOT NULL,
    department      VARCHAR(100) NOT NULL,
    semester        TINYINT UNSIGNED NOT NULL,
    address         VARCHAR(255) NOT NULL,
    enrollment_date DATE         NOT NULL,
    status          ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
    created_at      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_students_roll  UNIQUE (roll_number),
    CONSTRAINT uq_students_email UNIQUE (email),
    CONSTRAINT chk_students_semester CHECK (semester BETWEEN 1 AND 8),
    INDEX idx_students_name (full_name),
    INDEX idx_students_department (department),
    INDEX idx_students_semester (semester),
    INDEX idx_students_created (created_at)
) ENGINE=InnoDB;

-- -------------------------------------------------------------------------------------
-- 3. courses
-- -------------------------------------------------------------------------------------
CREATE TABLE courses (
    id              BIGINT       NOT NULL AUTO_INCREMENT,
    course_code     VARCHAR(20)  NOT NULL,
    course_name     VARCHAR(150) NOT NULL,
    department      VARCHAR(100) NOT NULL,
    semester        TINYINT UNSIGNED NOT NULL,
    credits         TINYINT UNSIGNED NOT NULL,
    instructor_name VARCHAR(100) NOT NULL,
    description     TEXT         NULL,
    created_at      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_courses_code UNIQUE (course_code),
    CONSTRAINT chk_courses_semester CHECK (semester BETWEEN 1 AND 8),
    CONSTRAINT chk_courses_credits  CHECK (credits BETWEEN 1 AND 10),
    INDEX idx_courses_dept_sem (department, semester)
) ENGINE=InnoDB;

-- -------------------------------------------------------------------------------------
-- 4. student_courses  (allocation of courses to students - many-to-many)
-- -------------------------------------------------------------------------------------
CREATE TABLE student_courses (
    id           BIGINT   NOT NULL AUTO_INCREMENT,
    student_id   BIGINT   NOT NULL,
    course_id    BIGINT   NOT NULL,
    allocated_on DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_student_course UNIQUE (student_id, course_id),
    CONSTRAINT fk_sc_student FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT fk_sc_course  FOREIGN KEY (course_id)  REFERENCES courses (id)  ON DELETE CASCADE,
    INDEX idx_sc_course (course_id)
) ENGINE=InnoDB;

-- -------------------------------------------------------------------------------------
-- 5. attendance  (one row per student, course and date)
-- -------------------------------------------------------------------------------------
CREATE TABLE attendance (
    id              BIGINT   NOT NULL AUTO_INCREMENT,
    student_id      BIGINT   NOT NULL,
    course_id       BIGINT   NOT NULL,
    attendance_date DATE     NOT NULL,
    status          ENUM('PRESENT','ABSENT','LEAVE') NOT NULL,
    marked_at       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_attendance UNIQUE (student_id, course_id, attendance_date),
    CONSTRAINT fk_att_student FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT fk_att_course  FOREIGN KEY (course_id)  REFERENCES courses (id)  ON DELETE CASCADE,
    INDEX idx_att_course_date (course_id, attendance_date),
    INDEX idx_att_date (attendance_date)
) ENGINE=InnoDB;

-- -------------------------------------------------------------------------------------
-- 6. results  (one row per student and course; grade and pass/fail are derived in Java)
-- -------------------------------------------------------------------------------------
CREATE TABLE results (
    id             BIGINT       NOT NULL AUTO_INCREMENT,
    student_id     BIGINT       NOT NULL,
    course_id      BIGINT       NOT NULL,
    marks_obtained DECIMAL(6,2) NOT NULL,
    max_marks      DECIMAL(6,2) NOT NULL DEFAULT 100.00,
    created_at     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_result UNIQUE (student_id, course_id),
    CONSTRAINT fk_res_student FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT fk_res_course  FOREIGN KEY (course_id)  REFERENCES courses (id)  ON DELETE CASCADE,
    CONSTRAINT chk_res_max   CHECK (max_marks > 0),
    CONSTRAINT chk_res_marks CHECK (marks_obtained >= 0 AND marks_obtained <= max_marks),
    INDEX idx_res_course (course_id)
) ENGINE=InnoDB;

